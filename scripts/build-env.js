'use strict';

/**
 * Zero-dependency build helper:
 * 1. Reads SUPABASE_URL & SUPABASE_PUBLISHABLE_KEY from process.env or local .env
 * 2. Writes js/config/env.generated.js (for local preview & bundling)
 * 3. Assembles clean static production output into public/ (for Vercel/Netlify/Cloudflare Pages)
 */
const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const envPath = path.join(rootDir, '.env');
const localEnvOut = path.join(rootDir, 'js', 'config', 'env.generated.js');
const publicDir = path.join(rootDir, 'public');

/**
 * Parse a simple KEY=VALUE .env file.
 * @param {string} content
 * @returns {Record<string, string>}
 */
function parseDotEnv(content) {
  const parsed = {};
  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const eqIdx = line.indexOf('=');
    if (eqIdx <= 0) continue;
    const key = line.slice(0, eqIdx).trim();
    let val = line.slice(eqIdx + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    parsed[key] = val;
  }
  return parsed;
}

const fileEnv = fs.existsSync(envPath)
  ? parseDotEnv(fs.readFileSync(envPath, 'utf8'))
  : {};

const supabaseUrl = (process.env.SUPABASE_URL || fileEnv.SUPABASE_URL || '').trim();
const publishableKey = (
  process.env.SUPABASE_PUBLISHABLE_KEY ||
  fileEnv.SUPABASE_PUBLISHABLE_KEY ||
  ''
).trim();

if (publishableKey.startsWith('sb_secret_')) {
  console.error('ERROR: Jangan masukkan sb_secret_ key ke frontend! Gunakan sb_publishable_ key.');
  process.exit(1);
}

const envScriptContent = [
  "'use strict';",
  '// Auto-generated by scripts/build-env.js (gitignored)',
  `window.__ZERO_FIVE_ENV__ = ${JSON.stringify(
    {
      SUPABASE_URL: supabaseUrl,
      SUPABASE_PUBLISHABLE_KEY: publishableKey,
    },
    null,
    2
  )};`,
  '',
].join('\n');

// 1. Write local env.generated.js
fs.mkdirSync(path.dirname(localEnvOut), { recursive: true });
fs.writeFileSync(localEnvOut, envScriptContent, 'utf8');

// 2. Build clean public/ output directory (only frontend runtime + PWA assets)
fs.rmSync(publicDir, { recursive: true, force: true });
fs.mkdirSync(publicDir, { recursive: true });
fs.copyFileSync(path.join(rootDir, 'index.html'), path.join(publicDir, 'index.html'));
fs.copyFileSync(
  path.join(rootDir, 'manifest.webmanifest'),
  path.join(publicDir, 'manifest.webmanifest')
);
fs.copyFileSync(path.join(rootDir, 'sw.js'), path.join(publicDir, 'sw.js'));
fs.cpSync(path.join(rootDir, 'css'), path.join(publicDir, 'css'), { recursive: true });
fs.cpSync(path.join(rootDir, 'js'), path.join(publicDir, 'js'), { recursive: true });
if (fs.existsSync(path.join(rootDir, 'assets'))) {
  fs.cpSync(path.join(rootDir, 'assets'), path.join(publicDir, 'assets'), { recursive: true });
}

console.log(
  `Built public/ & js/config/env.generated.js (Supabase: ${supabaseUrl ? 'CONFIGURED' : 'EMPTY'})`
);
