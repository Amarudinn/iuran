'use strict';

/**
 * Zero-dependency build helper that reads SUPABASE_URL & SUPABASE_PUBLISHABLE_KEY
 * from process.env (CI/Vercel/Netlify) or local .env and writes js/config/env.generated.js.
 */
const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const envPath = path.join(rootDir, '.env');
const outputPath = path.join(rootDir, 'js', 'config', 'env.generated.js');

/**
 * Parse a simple KEY=VALUE .env file.
 * @param {string} content
 * @returns {Record<string, string>}
 */
function parseDotEnv(content) {
  const parsed = {};
  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const eqIdx = line.indexOf('=');
    if (eqIdx <= 0) continue;
    const key = line.slice(0, eqIdx).trim();
    let val = line.slice(eqIdx + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    parsed[key] = val;
  }
  return parsed;
}

const fileEnv = fs.existsSync(envPath)
  ? parseDotEnv(fs.readFileSync(envPath, 'utf8'))
  : {};

const supabaseUrl = (process.env.SUPABASE_URL || fileEnv.SUPABASE_URL || '').trim();
const publishableKey = (
  process.env.SUPABASE_PUBLISHABLE_KEY ||
  fileEnv.SUPABASE_PUBLISHABLE_KEY ||
  ''
).trim();

if (publishableKey.startsWith('sb_secret_')) {
  console.error('ERROR: Jangan masukkan sb_secret_ key ke frontend! Gunakan sb_publishable_ key.');
  process.exit(1);
}

const outputContent = [
  "'use strict';",
  '// Auto-generated by scripts/build-env.js (gitignored)',
  `window.__ZERO_FIVE_ENV__ = ${JSON.stringify(
    {
      SUPABASE_URL: supabaseUrl,
      SUPABASE_PUBLISHABLE_KEY: publishableKey,
    },
    null,
    2
  )};`,
  '',
].join('\n');

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, outputContent, 'utf8');

console.log(
  `Generated js/config/env.generated.js (Supabase: ${supabaseUrl ? 'CONFIGURED' : 'EMPTY'})`
);
